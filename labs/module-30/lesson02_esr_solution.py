"""Lesson 30.2 (reference solution): ESR hyperfine structure of the methyl radical and the hydrogen atom.

Run from this folder:
    py lesson02_esr_solution.py
Files: esr_methyl_example.csv and esr_hydrogen_example.csv (columns B_mT,dchi_dB: first-derivative X-band
spectra at 9.4500 GHz, GENERATED by make_data.py from published constants).
Part 1: methyl radical: line positions, g and a_H, binomial intensities, the CD3 prediction.
Part 2: hydrogen atom: first-order prediction against the exact (Breit-Rabi) positions.
Writes runs/lesson02_esr.png.
"""
import numpy as np
from scipy.optimize import brentq
from scipy.signal import find_peaks

from pc30 import HERE, H, MU_B, MU_N, G_P, G_D, read_csv, column, linfit, todo, save_plot, pyplot

NU = 9.4500e9            # Hz, microwave frequency of the example spectra
A_H_HZ = 1420.405751768e6
G_H_ATOM = 2.0022838     # bound-electron g of the hydrogen atom


# ---------------- given ----------------
def line_centres(B, s):
    """Centres of derivative lines: the zero crossing between each positive lobe and the negative lobe after it."""
    hi, _ = find_peaks(s, height=0.08 * s.max(), prominence=0.05 * s.max())
    lo, _ = find_peaks(-s, height=0.08 * s.max(), prominence=0.05 * s.max())
    out, amp = [], []
    for i in hi:
        later = lo[lo > i]
        if len(later) == 0:
            continue
        j = later[0]
        k = i + int(np.argmin(np.abs(s[i:j + 1])))
        k = min(max(k, i + 1), j)
        b0, b1, y0, y1 = B[k - 1], B[k], s[k - 1], s[k]
        out.append(b0 - y0 * (b1 - b0) / (y1 - y0) if y1 != y0 else B[k])
        amp.append(s[i] - s[j])                      # peak-to-peak height
    return np.array(out), np.array(amp)


def h_atom_exact_fields(nu=NU):
    """Exact resonance fields (mT) of the free H atom from the 4x4 spin Hamiltonian (Breit-Rabi)."""
    def trans(B, mi):
        A = H * A_H_HZ
        ez, nz = G_H_ATOM * MU_B * B, G_P * MU_N * B
        Hm = np.zeros((4, 4))
        for n, (ms, m) in enumerate(((0.5, 0.5), (0.5, -0.5), (-0.5, 0.5), (-0.5, -0.5))):
            Hm[n, n] = ez * ms - nz * m + A * ms * m
        Hm[1, 2] = Hm[2, 1] = A / 2
        E, V = np.linalg.eigh(Hm)
        up, dn = {0.5: (0, 2), -0.5: (1, 3)}[mi]
        return (E[int(np.argmax(np.abs(V[up])))] - E[int(np.argmax(np.abs(V[dn])))]) / H - nu
    return sorted(brentq(trans, 0.25, 0.42, args=(mi,)) * 1e3 for mi in (0.5, -0.5))


# ---------------- the physics ----------------
def field_for_g(nu, g):
    """Resonance field in mT for a free spin with factor g at microwave frequency nu (Hz): h nu = g mu_B B."""
    return H * nu / (g * MU_B) * 1e3


def multiplet(n, I=0.5):
    """Relative intensities of the lines from n equivalent nuclei of spin I: convolve n copies of
    [1, 1, ..., 1] (2I + 1 ones). n = 3, I = 1/2 gives 1 3 3 1."""
    out = np.array([1.0])
    for _ in range(n):
        out = np.convolve(out, np.ones(int(round(2 * I)) + 1))
    return out


def g_and_a(centres, mI):
    """Straight line B = B0 + a mI through the line centres: returns (g, a in mT, sigma_a)."""
    B0, a, sB0, sa, _, _ = linfit(mI, centres)
    return H * NU / (B0 * 1e-3 * MU_B), a, sa


def main():
    rows = read_csv(HERE / "esr_methyl_example.csv")
    B, s = column(rows, "B_mT"), column(rows, "dchi_dB")
    c, amp = line_centres(B, s)
    mI = np.arange(len(c)) - (len(c) - 1) / 2
    ga = g_and_a(c, mI)
    I3 = multiplet(3)
    B_free = field_for_g(NU, 2.00231930436)
    if todo(ga, I3, B_free):
        return
    g, a, sa = ga
    print(f"Part 1: methyl radical, {len(c)} lines at {', '.join(f'{x:.3f}' for x in c)} mT")
    print(f"  g = {g:.5f} (free electron 2.00232; resonance of a free electron here {B_free:.2f} mT)")
    print(f"  |a_H| = {a:.3f} +/- {sa:.3f} mT = {a * 1e-3 * g * MU_B / H / 1e6:.1f} MHz")
    print(f"  peak-to-peak heights normalised: {', '.join(f'{x:.2f}' for x in amp / amp.min())} "
          f"(binomial {' : '.join(f'{x:.0f}' for x in I3)})")
    aD = a * G_D / G_P
    I_cd3 = multiplet(3, 1)
    print(f"  CD3 prediction: {len(I_cd3)} lines, a_D = {aD:.3f} mT, intensities {' : '.join(f'{x:.0f}' for x in I_cd3)}, "
          f"total width {aD * (len(I_cd3) - 1):.2f} mT")

    rows = read_csv(HERE / "esr_hydrogen_example.csv")
    Bh, sh = column(rows, "B_mT"), column(rows, "dchi_dB")
    ch, _ = line_centres(Bh, sh)
    a_first = H * A_H_HZ / (G_H_ATOM * MU_B) * 1e3
    B0_first = field_for_g(NU, G_H_ATOM)
    exact = h_atom_exact_fields()
    print(f"\nPart 2: hydrogen atom, lines at {ch[0]:.2f} and {ch[1]:.2f} mT: spacing {ch[1] - ch[0]:.2f} mT, "
          f"centre {ch.mean():.2f} mT")
    print(f"  first order: a = hA/(g mu_B) = {a_first:.2f} mT, lines at {B0_first - a_first / 2:.2f} and "
          f"{B0_first + a_first / 2:.2f} mT (centre {B0_first:.2f})")
    print(f"  exact Breit-Rabi: {exact[0]:.2f} and {exact[1]:.2f} mT; centre shifted by "
          f"{np.mean(exact) - B0_first:+.2f} mT, spacing {exact[1] - exact[0] - a_first:+.2f} mT vs first order")
    print(f"  a naive g from the observed centre would be {H * NU / (ch.mean() * 1e-3 * MU_B):.5f} instead of {G_H_ATOM}")

    plt = pyplot()
    if plt is None:
        return
    fig, (a1, a2) = plt.subplots(1, 2, figsize=(10, 3.6))
    a1.plot(B, s, lw=0.8)
    for x in c:
        a1.axvline(x, color="grey", lw=0.5, ls=":")
    a1.set_xlabel("B (mT)")
    a1.set_ylabel("first derivative")
    a1.set_title("CH$_3$, 9.45 GHz")
    a2.plot(Bh, sh, lw=0.8)
    for x in (B0_first - a_first / 2, B0_first + a_first / 2):
        a2.axvline(x, color="red", lw=0.8, ls="--")
    a2.set_xlabel("B (mT)")
    a2.set_title("H atom (dashed: first order)")
    save_plot(fig, "lesson02_esr.png")


if __name__ == "__main__":
    main()
