"""Lesson 30.3 (reference solution): speed of sound in a tube and the heat-capacity ratio of air.

Run from this folder:
    py lesson03_sound_solution.py
    py lesson03_sound_solution.py my_tube.csv 22.5 0.45 100.8 0.019
        (your series; air temperature C, relative humidity 0-1, pressure kPa, tube inner radius m)
    py lesson03_sound_solution.py spectrum my_audio_spectrum.csv
        (only list the resonance peaks of one phyphox Audio Spectrum export)
Files: tube_resonance_example.csv (columns length_m,mode_n,f_Hz; tube closed at one end, GENERATED by
make_data.py) and audio_spectrum_example.csv (a phyphox-style Audio Spectrum export, GENERATED).
Writes runs/lesson03_sound.png.
"""
import math
import sys
from pathlib import Path

import numpy as np
from scipy.signal import find_peaks

from pc30 import HERE, R, read_csv, column, linfit, propagate, todo, save_plot, pyplot

M_DRY = 28.9647e-3       # kg/mol, dry air (CO2 about 420 ppm)
M_WATER = 18.0153e-3     # kg/mol


# ---------------- given ----------------
def spectrum_peaks(path, n_peaks=4):
    """Frequencies of the strongest resonance peaks in an Audio Spectrum export (first two numeric
    columns: frequency in Hz, amplitude), refined with a three-point parabola."""
    with open(path, encoding="utf-8") as fh:
        rows = [line.strip().replace(";", ",").split(",") for line in fh if line.strip() and not line.startswith("#")]
    data = []
    for r in rows:
        try:
            data.append((float(r[0].strip('"')), float(r[1].strip('"'))))
        except (ValueError, IndexError):
            continue                                  # header line
    f, a = np.array(data).T
    idx, props = find_peaks(a, prominence=0.1 * a.max())
    idx = idx[np.argsort(props["prominences"])[::-1][:n_peaks]]
    out = []
    for i in sorted(idx):
        y0, y1, y2 = a[i - 1], a[i], a[i + 1]
        out.append(f[i] + 0.5 * (y0 - y2) / (y0 - 2 * y1 + y2) * (f[1] - f[0]))
    return np.array(out)


# ---------------- the physics ----------------
def speed_from_series(L, n, f):
    """Closed tube: f = n c / (4 (L + e)) for n = 1, 3, 5, ...  Rearranged, L = c (n / 4f) - e, a straight
    line in x = n / (4 f). Returns (c, sigma_c, e, sigma_e)."""
    x = np.asarray(n) / (4 * np.asarray(f))
    a, b, sa, sb, _, _ = linfit(x, L)
    return b, sb, -a, sa


def moist_air_molar_mass(T_C, RH, p_kPa):
    """Molar mass of humid air (kg/mol). Water mole fraction x = RH p_sat / p with the Buck (1981) saturation
    pressure p_sat = 0.61121 exp((18.678 - T/234.5) (T / (257.14 + T))) kPa, T in C."""
    p_sat = 0.61121 * math.exp((18.678 - T_C / 234.5) * (T_C / (257.14 + T_C)))
    x = RH * p_sat / p_kPa
    return (1 - x) * M_DRY + x * M_WATER


def gamma_from_speed(c, T_K, M):
    """Ideal gas: c = sqrt(gamma R T / M), so gamma = M c^2 / (R T)."""
    return M * c**2 / (R * T_K)


def main():
    if len(sys.argv) > 2 and sys.argv[1] == "spectrum":
        print("peaks (Hz):", ", ".join(f"{x:.1f}" for x in spectrum_peaks(Path(sys.argv[2]))))
        return
    path = Path(sys.argv[1]) if len(sys.argv) > 1 else HERE / "tube_resonance_example.csv"
    T_C, RH, P, RADIUS = (float(v) for v in sys.argv[2:6]) if len(sys.argv) > 5 else (23.0, 0.50, 101.0, 0.0200)

    pk = spectrum_peaks(HERE / "audio_spectrum_example.csv")
    print(f"Part 1: example Audio Spectrum (0.500 m tube): peaks at {', '.join(f'{x:.1f}' for x in pk)} Hz, "
          f"ratios {', '.join(f'{x / pk[0]:.2f}' for x in pk)} (closed tube: 1, 3, 5, 7)")

    rows = read_csv(path)
    L, n, f = column(rows, "length_m"), column(rows, "mode_n"), column(rows, "f_Hz")
    fit = speed_from_series(L, n, f)
    M = moist_air_molar_mass(T_C, RH, P)
    g_test = gamma_from_speed(343.2, 293.15, M_DRY)
    if todo(fit, M, g_test):
        return
    c, sc, e, se = fit
    print(f"Part 2: {len(L)} resonances. c = {c:.2f} +/- {sc:.2f} m/s; end correction e = {e * 1000:.1f} +/- "
          f"{se * 1000:.1f} mm (theory 0.6133 r = {0.6133 * RADIUS * 1000:.1f} mm)")
    naive = 4 * L[n == 1] * f[n == 1]
    print(f"  without the end correction, c = 4 L f1 would give {', '.join(f'{x:.0f}' for x in naive)} m/s")
    print(f"  check: dry air at 20 C and 343.2 m/s gives gamma = {g_test:.4f}")
    gam, sg = propagate(lambda c, T, RH: gamma_from_speed(c, T + 273.15, moist_air_molar_mass(T, RH, P)),
                        {"c": (c, sc), "T": (T_C, 0.5), "RH": (RH, 0.10)})
    print(f"Part 3: air at {T_C} C, RH {RH * 100:.0f} %: M = {M * 1000:.3f} g/mol; gamma = {gam:.4f} +/- {sg:.4f}")
    print(f"  Cv,m = R/(gamma - 1) = {1 / (gam - 1):.2f} R  (rigid diatomic 2.50 R, gamma 1.400)")
    for name, val in (("c", sc / c * 2), ("T (0.5 K)", 0.5 / (T_C + 273.15))):
        print(f"  relative contribution to gamma from {name}: {val * 100:.2f} %")

    plt = pyplot()
    if plt is None:
        return
    fig, ax = plt.subplots(figsize=(5.5, 4))
    x = n / (4 * f)
    for k, mk in ((1, "o"), (3, "s"), (5, "^")):
        ax.plot(x[n == k] * 1000, L[n == k], mk, label=f"n = {k}")
    xx = np.linspace(0, x.max(), 10)
    ax.plot(xx * 1000, c * xx - e, "k--", lw=0.8, label=f"c = {c:.1f} m/s")
    ax.set_xlabel("n / (4 f)  (ms)")
    ax.set_ylabel("tube length L (m)")
    ax.legend()
    save_plot(fig, "lesson03_sound.png")


if __name__ == "__main__":
    main()
