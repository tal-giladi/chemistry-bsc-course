"""Generate the Module 30 example data (seeded). Run: py make_data.py

Every file written here is realistic but NOT measured. The true values below are what a correct analysis
should recover, within the noise. The published dye data (cyanine_dyes.csv) are NOT generated here.

Model values and their sources (checked 2026-10-17):
- HCl: NIST WebBook constants of H35Cl (pc30.HCL35); H37Cl by isotope scaling with NIST atomic masses.
  Line positions from these constants agree with the measured FTIR lines (Rank et al. 1965; Guelachvili
  et al. 1981) to a few hundredths of a cm^-1. Intensities: Boltzmann population x |m| x wavenumber,
  no Herman-Wallis factor. The overtone region is scaled as if recorded with a 50 times longer path.
- Methyl radical: g = 2.00255, |a_H| = 2.304 mT (Fessenden and Schuler, J. Chem. Phys. 39, 2147 (1963)).
- Hydrogen atom: zero-field hyperfine splitting 1420.405751768 MHz; bound-electron g_J = 2.0022838
  (g_e (1 - alpha^2/3)); proton g factor CODATA 2022; exact (Breit-Rabi) resonance fields.
- Sound: ideal gas, dry air gamma 1.4000, water vapour gamma 1.33, Buck (1981) saturation pressure,
  unflanged end correction 0.6133 r (Levine and Schwinger 1948).
"""
import csv
import math

import numpy as np
from scipy.optimize import brentq

from pc30 import (HERE, H, C_CM, K_B, R, MU_B, MU_N, G_P, HC_K, HCL35, ABUNDANCE_35CL,
                  reduced_mass, isotope_constants, term)

rng = np.random.default_rng(30)


def write(name, header, rows, comments=()):
    with open(HERE / name, "w", newline="", encoding="utf-8") as fh:
        for c in comments:
            fh.write(f"# {c}\n")
        w = csv.writer(fh, lineterminator="\n")
        w.writerow(header)
        w.writerows(rows)
    print("wrote", name, len(rows), "rows")


def lorentz(x, x0, fwhm):
    return 1.0 / (1.0 + ((x - x0) / (fwhm / 2)) ** 2)


# ---------------- 30.1 HCl FTIR spectrum ----------------
T_GAS = 296.0
FWHM = 0.25                     # cm^-1, pressure + instrument
STEP = 0.08                     # cm^-1 point spacing
rho = math.sqrt(reduced_mass("H", "35Cl") / reduced_mass("H", "37Cl"))
ISO = {"H35Cl": (HCL35, ABUNDANCE_35CL), "H37Cl": (isotope_constants(HCL35, rho), 1 - ABUNDANCE_35CL)}


def band_lines(const, v_up, jmax=14):
    out = []
    for J in range(jmax + 1):
        pop = (2 * J + 1) * math.exp(-HC_K * (term(const, 0, J) - term(const, 0, 0)) / T_GAS)
        nu_r = term(const, v_up, J + 1) - term(const, 0, J)
        out.append((nu_r, pop * (J + 1) / (2 * J + 1) * nu_r))
        if J >= 1:
            nu_p = term(const, v_up, J - 1) - term(const, 0, J)
            out.append((nu_p, pop * J / (2 * J + 1) * nu_p))
    return out


rows = []
for lo, hi, v_up, scale in ((2650.0, 3080.0, 1, 1.0), (5560.0, 5800.0, 2, 1.0 / 2.0)):
    x = np.arange(lo, hi + STEP / 2, STEP)
    y = 0.004 + 0.00001 * (x - lo)                      # small sloping baseline
    lines = []
    for name, (const, ab) in ISO.items():
        lines += [(nu, s * ab) for nu, s in band_lines(const, v_up)]
    smax = max(s for _, s in lines)
    for nu, s in lines:
        y = y + scale * 0.9 * s / smax * lorentz(x, nu, FWHM)
    y = y + rng.normal(0, 0.002, x.size)
    rows += [[f"{a:.3f}", f"{b:.4f}"] for a, b in zip(x, y)]
write("hcl_ftir_example.csv", ["wavenumber_cm1", "absorbance"], rows, [
    "Example HCl gas-phase FTIR absorbance spectrum, natural isotopes, 296 K. GENERATED by make_data.py from",
    "NIST WebBook constants of H35Cl (isotope-scaled for H37Cl); not a measured spectrum. Point spacing 0.08 cm-1,",
    "line FWHM 0.25 cm-1. Regions: fundamental 2650-3080 cm-1 and first overtone 5560-5800 cm-1 (long path)."])

# ---------------- 30.2 ESR spectra ----------------
NU_X = 9.4500e9                 # Hz, X band


def deriv_lorentz(B, B0, dBpp):
    """First derivative of a Lorentzian absorption line with peak-to-peak width dBpp (same units as B)."""
    g = dBpp * math.sqrt(3) / 2  # half width at half maximum
    xx = (B - B0) / g
    return -2 * xx / (1 + xx**2) ** 2


G_CH3, A_CH3 = 2.00255, 2.304   # -, mT
B_c = H * NU_X / (G_CH3 * MU_B) * 1e3
Bx = np.arange(328.0, 346.0, 0.005)
sig = np.zeros_like(Bx)
for k, w in zip((-1.5, -0.5, 0.5, 1.5), (1, 3, 3, 1)):
    sig += w * deriv_lorentz(Bx, B_c + A_CH3 * k, 0.060)
sig = sig / np.abs(sig).max() + rng.normal(0, 0.01, Bx.size)
write("esr_methyl_example.csv", ["B_mT", "dchi_dB"], [[f"{a:.3f}", f"{b:.4f}"] for a, b in zip(Bx, sig)], [
    "Example X-band ESR spectrum (first derivative) of the methyl radical, microwave frequency 9.4500 GHz.",
    "GENERATED by make_data.py from g = 2.00255 and |a_H| = 2.304 mT (Fessenden and Schuler 1963); first order."])

A_H_HZ, G_J = 1420.405751768e6, 2.0022838


def h_atom_levels(B):
    """Energies (J) and eigenvectors of the hydrogen-atom spin Hamiltonian in the |mS mI> basis
    order (+,+), (+,-), (-,+), (-,-)."""
    A = H * A_H_HZ
    ez, nz = G_J * MU_B * B, G_P * MU_N * B
    Hm = np.zeros((4, 4))
    for i, (ms, mi) in enumerate(((0.5, 0.5), (0.5, -0.5), (-0.5, 0.5), (-0.5, -0.5))):
        Hm[i, i] = ez * ms - nz * mi + A * ms * mi
    Hm[1, 2] = Hm[2, 1] = A / 2      # flip-flop term of S.I
    return np.linalg.eigh(Hm)


def h_transition(B, mi):
    E, V = h_atom_levels(B)
    up = {0.5: 0, -0.5: 1}[mi]      # |+, mi>
    dn = {0.5: 2, -0.5: 3}[mi]      # |-, mi>
    iu = int(np.argmax(np.abs(V[up, :])))
    idn = int(np.argmax(np.abs(V[dn, :])))
    return (E[iu] - E[idn]) / H


B_lines = [brentq(lambda b: h_transition(b, mi) - NU_X, 0.25, 0.42) * 1e3 for mi in (-0.5, 0.5)]
Bh = np.arange(300.0, 375.0, 0.02)
sig = sum(deriv_lorentz(Bh, b, 0.12) for b in B_lines)
sig = sig / np.abs(sig).max() + rng.normal(0, 0.01, Bh.size)
write("esr_hydrogen_example.csv", ["B_mT", "dchi_dB"], [[f"{a:.3f}", f"{b:.4f}"] for a, b in zip(Bh, sig)], [
    "Example X-band ESR spectrum (first derivative) of hydrogen atoms trapped in a solid, 9.4500 GHz.",
    "GENERATED by make_data.py with the exact (Breit-Rabi) resonance fields of the free atom:",
    f"{B_lines[0]:.3f} and {B_lines[1]:.3f} mT."])

# ---------------- 30.3 tube resonance ----------------
T_C, RH, P_KPA, RADIUS = 23.0, 0.50, 101.0, 0.0200
p_sat = 0.61121 * math.exp((18.678 - T_C / 234.5) * (T_C / (257.14 + T_C)))
x_w = RH * p_sat / P_KPA
M_moist = (28.9647 * (1 - x_w) + 18.0153 * x_w) * 1e-3
cv = 2.5 * (1 - x_w) + (1 / 0.33) * x_w
gamma_true = 1 + 1 / cv
c_true = math.sqrt(gamma_true * R * (T_C + 273.15) / M_moist)
end = 0.6133 * RADIUS
rows = []
for L in (0.300, 0.400, 0.500, 0.600, 0.700):
    for n in (1, 3, 5):
        f = n * c_true / (4 * (L + end)) * (1 + rng.normal(0, 0.003))
        rows.append([f"{L:.3f}", n, f"{f:.1f}"])
write("tube_resonance_example.csv", ["length_m", "mode_n", "f_Hz"], rows, [
    f"Example resonance series: tube closed at one end, inner radius {RADIUS * 100:.1f} cm, air {T_C} C, "
    f"RH {RH * 100:.0f} %, {P_KPA} kPa.",
    "Length measured from the closed end to the open rim. GENERATED by make_data.py "
    f"(true c = {c_true:.2f} m/s, gamma = {gamma_true:.4f}, M = {M_moist * 1e3:.3f} g/mol)."])

L_spec = 0.500
f_ax = np.arange(0, 3000, 2.93)
amp = 1e-4 * (1 + 0.2 * rng.random(f_ax.size))
for n, h in ((1, 1.0), (3, 0.55), (5, 0.30), (7, 0.12)):
    f_n = n * c_true / (4 * (L_spec + end))
    amp += 0.02 * h * lorentz(f_ax, f_n, 25 + 4 * n)
write("audio_spectrum_example.csv", ["Frequency (Hz)", "Amplitude"],
      [[f"{a:.2f}", f"{b:.6f}"] for a, b in zip(f_ax, amp)], [
    "Example of a phyphox Audio Spectrum export (16384 samples at 48 kHz, 2.93 Hz bins) for the 0.500 m tube",
    "excited by finger snaps at the open end. GENERATED by make_data.py; column names may differ in your export."])
print(f"true values: c = {c_true:.2f} m/s, gamma = {gamma_true:.4f}, end correction {end * 1000:.1f} mm, "
      f"H atom lines {B_lines[0]:.3f} / {B_lines[1]:.3f} mT, methyl centre {B_c:.3f} mT")
