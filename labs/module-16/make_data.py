"""Regenerate the generated example data for Module 16 (fixed random seed, so the files do not change).

    py make_data.py

mutarotation_example.csv: optical rotation of a freshly dissolved alpha-D-glucopyranose solution in a
polarimeter, as specific rotation [alpha]D (deg mL g^-1 dm^-1) against time. Model: first-order approach
to equilibrium, [a](t) = a_eq + (a_0 - a_eq) exp(-k t), with a_0 = +112.2, a_eq = +52.6 (OpenStax
Organic Chemistry 25.5), k = 0.0120 min^-1 (an illustrative value of the right order for water near
room temperature), the first reading taken 1.5 min after dissolving, and Gaussian reading noise of
0.3 deg. Realistic but not measured."""
import csv
import math
import random
from pathlib import Path

HERE = Path(__file__).resolve().parent


def mutarotation():
    rng = random.Random(16)
    a0, aeq, k = 112.2, 52.6, 0.0120
    rows = []
    for t in [1.5, 5, 10, 15, 20, 30, 40, 50, 60, 75, 90, 120, 150, 180, 240, 300, 360, 480]:
        a = aeq + (a0 - aeq) * math.exp(-k * t) + rng.gauss(0, 0.3)
        rows.append((t, round(a, 1)))
    with open(HERE / "mutarotation_example.csv", "w", newline="\n", encoding="utf-8") as f:
        f.write("# Generated by make_data.py (model, not a measurement). Columns: time in minutes, specific rotation.\n")
        w = csv.writer(f, lineterminator="\n")
        w.writerow(["t_min", "alpha_deg"])
        w.writerows(rows)


if __name__ == "__main__":
    mutarotation()
    print("wrote mutarotation_example.csv")
