def bv_fit(E, i, Ru):
    """Full fit: E = eta + i Ru with i = i0 [exp(aa f eta) - exp(-ac f eta)]. Returns (i0, aa, ac)."""
    def model(p):
        lg, aa, ac = p
        out = []
        for e in E:
            g = lambda x: 10**lg * (np.exp(aa * FRT * (e - x * Ru)) - np.exp(-ac * FRT * (e - x * Ru))) - x
            out.append(brentq(g, -5, 5, xtol=1e-14))
        return np.array(out)
    res = least_squares(lambda p: (model(p) - i) / (np.abs(i) + 1e-6), [-6, 0.5, 0.5],
                        bounds=([-12, 0.1, 0.1], [-1, 0.9, 0.9]))
    lg, aa, ac = res.x
    return 10**lg, aa, ac


def main():
    path = Path(sys.argv[1]) if len(sys.argv) > 1 else HERE / "tafel_her.csv"
    Ru = float(sys.argv[2]) if len(sys.argv) > 2 else 2.5
    rows = read_csv(path)
    names = sorted(set(r["electrode"] for r in rows), key=[r["electrode"] for r in rows].index)
    E_all, i_all = column(rows, "E_V"), column(rows, "i_A_cm2")
    el = np.array([r["electrode"] for r in rows])
    first = el == names[0]
    if todo(i0_from_linear(E_all[first], i_all[first]),
            tafel_fit(E_all[first] - i_all[first] * Ru, i_all[first])):
        return
    plt = pyplot()
    fig, ax = (plt.subplots(figsize=(7, 4.5)) if plt else (None, None))
    print(f"F/RT = {FRT:.3f} 1/V; 2.303RT/F = {1000 * LN10 / FRT:.1f} mV; Ru = {Ru} ohm")
    for name in names:
        s = el == name
        E, i = E_all[s], i_all[s]
        eta = E - i * Ru
        i0_lin = i0_from_linear(E, i)
        b, i0_t, ac = tafel_fit(eta, i)
        b_raw, i0_raw, _ = tafel_fit(E, i, lo=-0.45, hi=-0.10)
        i0_f, aa_f, ac_f = bv_fit(E, i, Ru)
        print(f"{name}: R_ct = {R * T / (F * i0_lin):.0f} ohm cm2 -> i0 = {i0_lin:.2e} A/cm2 (micro-polarisation)")
        print(f"   Tafel (iR-corrected): b = {b:.0f} mV/dec, alpha_c = {ac:.2f}, i0 = {i0_t:.2e} A/cm2")
        print(f"   Tafel on raw E (no iR correction, to -0.45 V): b = {b_raw:.0f} mV/dec, i0 = {i0_raw:.2e} A/cm2")
        print(f"   full BV + iR fit: i0 = {i0_f:.2e}, alpha_a = {aa_f:.2f}, alpha_c = {ac_f:.2f}")
        print(f"   current at eta = -0.20 V: {i0_t * 10**(0.200 / (b / 1000)) * 1000:.2f} mA/cm2; "
              f"overpotential for 10 mA/cm2: {b / 1000 * np.log10(0.010 / i0_t) * 1000:.0f} mV")
        if ax is not None:
            ax.semilogy(E, np.abs(i), ".", ms=3, label=f"{name}, applied E")
            ax.semilogy(eta, np.abs(i), "-", label=f"{name}, iR-corrected")
    if ax is not None:
        ax.set_xlabel("potential or overpotential / V vs RHE")
        ax.set_ylabel("|i| / A cm$^{-2}$")
        ax.set_title("HER Tafel plots (generated data)")
        ax.legend(fontsize=8)
        save_plot(fig, "lesson01_tafel.png")


if __name__ == "__main__":
    main()
