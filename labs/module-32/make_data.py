"""Rebuild the GENERATED example data of Module 32 (seeded, so the files are reproducible):

    py make_data.py

tafel_her.csv        hydrogen evolution on Ni and Cu in 0.5 M H2SO4 (H2-saturated), 25 C, 1.00 cm2 electrode,
                     potential vs RHE, with 2.5 ohm uncompensated resistance. Butler-Volmer model; i0 and
                     alpha chosen inside the published spread for these metals (Trasatti 1972; Norskov 2005).
corrosion_steel.csv  carbon steel in 1 M HCl, 25 C, 1.00 cm2, potential vs SCE, 0.167 mV/s polarisation scan,
                     with and without a corrosion inhibitor (mixed-potential Butler-Volmer, 1.0 ohm).
The real XRD patterns are NOT made here: see get_zenodo_xrd.py.
"""
import numpy as np
from scipy.optimize import brentq

from ec32 import HERE, f_over_rt

RNG = np.random.default_rng(32)
FRT = f_over_rt(298.15)


def bv_current(eta, i0, alpha_a, alpha_c):
    return i0 * (np.exp(alpha_a * FRT * eta) - np.exp(-alpha_c * FRT * eta))


def solve_with_ir(E, current_of_eta, Ru):
    """Current at applied potential E when E = eta + i Ru (eta measured from the equilibrium potential)."""
    return brentq(lambda i: current_of_eta(E - i * Ru) - i, -10, 10, xtol=1e-14)


def noisy(i, rel=0.015, absolute=2e-7):
    return i * (1 + rel * RNG.standard_normal()) + absolute * RNG.standard_normal()


def her():
    lines = ["# GENERATED by make_data.py (seed 32): HER Butler-Volmer model, 25 C, A = 1.00 cm2, Ru = 2.5 ohm.",
             "# E_V is the applied potential vs RHE (not iR-corrected); i_A_cm2 negative = cathodic (H2 evolution).",
             "electrode,E_V,i_A_cm2"]
    for name, i0, aa, ac in (("Ni", 8.0e-6, 0.50, 0.50), ("Cu", 2.5e-7, 0.48, 0.52)):
        f = lambda eta: bv_current(eta, i0, aa, ac)
        for E in np.round(np.arange(0.030, -0.4501, -0.005), 3):
            i = solve_with_ir(E, f, 2.5)
            lines.append(f"{name},{E:.3f},{noisy(i):.4e}")
    (HERE / "tafel_her.csv").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")


def corrosion():
    lines = ["# GENERATED by make_data.py (seed 32): carbon steel in 1 M HCl, 25 C, A = 1.00 cm2, Ru = 1.0 ohm.",
             "# Mixed potential: anodic Fe -> Fe2+ + 2e-, cathodic 2H+ + 2e- -> H2. E_V vs SCE (applied).",
             "sample,E_V,i_A_cm2"]
    cases = (("bare", -0.470, 2.5e-4, 0.070, 0.120), ("inhibited", -0.455, 2.2e-5, 0.085, 0.130))
    for name, Ecorr, icorr, ba, bc in cases:
        f = lambda E: icorr * (10 ** ((E - Ecorr) / ba) - 10 ** (-(E - Ecorr) / bc))
        for E in np.round(np.arange(Ecorr - 0.250, Ecorr + 0.2501, 0.005), 3):
            i = brentq(lambda x: f(E - x * 1.0) - x, -10, 10, xtol=1e-14)
            lines.append(f"{name},{E:.3f},{noisy(i, 0.02, 3e-8):.4e}")
    (HERE / "corrosion_steel.csv").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")


if __name__ == "__main__":
    her()
    corrosion()
    print("wrote tafel_her.csv and corrosion_steel.csv")
