def tafel_extrapolation(E, i, Ecorr, lo=0.080, hi=0.200):
    """Fit log10|i| against E on both branches lo..hi volts from Ecorr. Return (beta_a, beta_c, icorr, Ecross),
    with the slopes in V/decade (both positive) and icorr (A/cm2) at the crossing point of the two lines."""
    an = (E > Ecorr + lo) & (E < Ecorr + hi) & (i > 0)
    ca = (E < Ecorr - lo) & (E > Ecorr - hi) & (i < 0)
    a1, s1, _, _ = linfit(E[an], np.log10(i[an]))
    a2, s2, _, _ = linfit(E[ca], np.log10(-i[ca]))
    Ex = (a2 - a1) / (s1 - s2)
    return 1 / s1, -1 / s2, 10 ** (a1 + s1 * Ex), Ex


