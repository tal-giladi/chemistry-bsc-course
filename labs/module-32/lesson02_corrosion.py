def find_ecorr(E, i):
    """Potential where the current changes sign (linear interpolation)."""
    k = np.where(np.diff(np.sign(i)) > 0)[0][0]
    return E[k] - i[k] * (E[k + 1] - E[k]) / (i[k + 1] - i[k])


def analyse(sample="bare", Ru=1.0, plot=True):
    rows = [r for r in read_csv(HERE / "corrosion_steel.csv") if r["sample"] == sample]
    E_app, i = column(rows, "E_V"), column(rows, "i_A_cm2")
    E = E_app - i * Ru
    Ecorr = find_ecorr(E, i)
    ba, bc, ic, Ex = tafel_extrapolation(E, i, Ecorr)
    sg, cr = stern_geary(E, i, Ecorr, ba, bc), corrosion_rate(ic)
    if todo(sg, cr):
        return None
    Rp, ic_sg = sg
    print(f"{sample}: Ecorr = {Ecorr * 1000:.0f} mV vs SCE; beta_a = {ba * 1000:.0f} mV/dec, "
          f"beta_c = {bc * 1000:.0f} mV/dec")
    print(f"   Tafel extrapolation: icorr = {ic * 1e6:.0f} uA/cm2 (lines cross at {Ex * 1000:.0f} mV) "
          f"-> {cr:.2f} mm/y")
    print(f"   Stern-Geary: Rp = {Rp:.0f} ohm cm2, icorr = {ic_sg * 1e6:.0f} uA/cm2 -> {corrosion_rate(ic_sg):.2f} mm/y")
    plt = pyplot() if plot else None
    if plt:
        fig, ax = plt.subplots(figsize=(6.5, 4.5))
        ax.semilogx(np.abs(i), E, ".", ms=3, label="iR-corrected data")
        ii = np.logspace(np.log10(ic) - 1, np.log10(ic) + 2, 50)
        ax.semilogx(ii, Ex + ba * np.log10(ii / ic), "r--", label="anodic Tafel line")
        ax.semilogx(ii, Ex - bc * np.log10(ii / ic), "g--", label="cathodic Tafel line")
        ax.axhline(Ecorr, color="0.6", lw=0.8)
        ax.set_xlabel("|i| / A cm$^{-2}$")
        ax.set_ylabel("E / V vs SCE")
        ax.set_title(f"Evans plot, steel in 1 M HCl ({sample}, generated data)")
        ax.legend(fontsize=8)
        save_plot(fig, f"lesson02_corrosion_{sample}.png")
    return dict(Ecorr=Ecorr, ba=ba, bc=bc, icorr=ic, icorr_sg=ic_sg, Rp=Rp)


