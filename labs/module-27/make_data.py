"""Generate the Module 27 point-charge models and the one reconstructed data set (seeded). Run: py make_data.py

Point-charge models (all checked 2026-10-17):
- Water, TIP3P: q(O) = -0.834 e, q(H) = +0.417 e, r(OH) = 0.9572 A, angle HOH = 104.52 deg
  (Jorgensen et al., J. Chem. Phys. 79, 926 (1983); parameters as listed in the LAMMPS manual,
  https://docs.lammps.org/Howto_tip3p.html). Lennard-Jones O-O: epsilon = 0.1521 kcal/mol, sigma = 3.1507 A.
- CO2: EPM2 charges q(O) = -0.3256 e, q(C) = +0.6512 e (Harris and Yung, J. Phys. Chem. 99, 12021 (1995), via the
  Towhee force-field page https://towhee.sourceforge.net/forcefields/epm.html), placed on the experimental
  geometry r(CO) = 1.162 A (NIST CCCBDB, Herzberg 1966).
- OH-: illustrative charges (O -1.40 e, H +0.40 e, r = 0.97 A) for the origin-dependence exercise only.

Example data (generated, NOT measured):
- microwave_example.csv: distance between neighbouring melted spots on a plate of chocolate in a 2450 MHz oven,
  six trials; true half-wavelength c/(2f) = 6.118 cm, reading error 0.3 cm (ruler and spot-centre judgement).

Reconstructed data (NOT the original measurements):
- hcl_debye_points.csv: dielectric constant of HCl gas at 1 atm at eight temperatures between 201 and 589 K,
  computed from the Debye fit A = 7.63 cm3/mol, mu = 1.050 D that NBS Circular 537 lists for Zahn's 1924
  measurements, with 0.4 % random noise added to (eps - 1). Zahn's individual points are not openly available,
  so this file lets you run the full analysis and check that you recover his fit.
"""
import csv
import numpy as np

from pc27 import HERE, N_A, K_B, EPS0, DEBYE, R, ATM, C_LIGHT

rng = np.random.default_rng(27)


def write(name, header, rows, comment):
    with open(HERE / name, "w", newline="", encoding="utf-8") as fh:
        for line in comment.strip().splitlines():
            fh.write("# " + line + "\n")
        w = csv.writer(fh, lineterminator="\n")
        w.writerow(header)
        w.writerows(rows)
    print("wrote", name, len(rows), "rows")


# ---------- point-charge models ----------
half = np.radians(104.52 / 2)
r_oh = 0.9572
water = [("O", 0.0, 0.0, 0.0, -0.834),
         ("H1", r_oh * np.sin(half), 0.0, r_oh * np.cos(half), 0.417),
         ("H2", -r_oh * np.sin(half), 0.0, r_oh * np.cos(half), 0.417)]
write("water_tip3p.csv", ["label", "x_A", "y_A", "z_A", "q_e"],
      [(l, f"{x:.5f}", f"{y:.5f}", f"{z:.5f}", q) for l, x, y, z, q in water],
      "Water, TIP3P point charges (Jorgensen et al. 1983; LAMMPS manual). Molecule in the xz plane, dipole along +z.\n"
      "Generated by make_data.py.")
co2 = [("O1", 0.0, 0.0, 1.162, -0.3256), ("C", 0.0, 0.0, 0.0, 0.6512), ("O2", 0.0, 0.0, -1.162, -0.3256)]
write("co2_point_charges.csv", ["label", "x_A", "y_A", "z_A", "q_e"], co2,
      "CO2, EPM2 charges (Harris and Yung 1995) on the experimental geometry r(CO) = 1.162 A (NIST CCCBDB).\n"
      "Generated by make_data.py.")
oh = [("O", 0.0, 0.0, 0.0, -1.40), ("H", 0.0, 0.0, 0.97, 0.40)]
write("oh_minus_illustrative.csv", ["label", "x_A", "y_A", "z_A", "q_e"], oh,
      "Hydroxide ion, ILLUSTRATIVE charges (net -1 e) for the origin-dependence exercise. Not a literature model.\n"
      "Generated by make_data.py.")

# ---------- 27.1 microwave oven ----------
half_wl = C_LIGHT / (2 * 2.45e9) * 100      # cm
write("microwave_example.csv", ["trial", "spacing_cm"],
      [(i + 1, f"{half_wl + 0.3 * rng.standard_normal():.1f}") for i in range(6)],
      "EXAMPLE data (generated by make_data.py, not measured): spacing of neighbouring melted spots, cm.\n"
      "Oven rating plate: 2450 MHz.")

# ---------- reconstructed Debye data for HCl ----------
A = 7.63e-6                                    # m3/mol
mu = 1.050 * DEBYE
B = N_A * mu ** 2 / (9 * EPS0 * K_B)           # m3 K / mol
rows = []
for T in (201, 240, 273, 313, 363, 423, 500, 589):
    P = A + B / T                              # molar polarisation, m3/mol
    x = P * ATM / (R * T)                      # (eps - 1)/(eps + 2) for an ideal gas at 1 atm
    em1 = 3 * x / (1 - x)
    em1 *= 1 + 0.004 * rng.standard_normal()
    rows.append((T, f"{em1 * 1e6:.1f}"))
write("hcl_debye_points.csv", ["T_K", "eps_minus_1_ppm"], rows,
      "HCl gas at 1 atm: (eps - 1) in parts per million. RECONSTRUCTED from the Debye fit of Zahn (1924) as listed in\n"
      "NBS Circular 537 (A = 7.63 cm3/mol, mu = 1.050 D), with 0.4 % noise. Not the original data. See make_data.py.")
