def read_csv(name):
    """Rows of a CSV file in this folder as a list of dicts (strings). Lines starting with # are skipped."""
    with open(HERE / name, newline="", encoding="utf-8") as f:
        lines = [ln for ln in f if not ln.startswith("#")]
    return list(csv.DictReader(lines))


def column(rows, key, cast=float):
    return np.array([cast(r[key]) for r in rows])


# ---------- rate laws (v = initial rate) ----------
def mm(S, V, K):
    """Michaelis-Menten: v = V S / (K + S)."""
    return V * S / (K + S)


def mixed(S, I, V, K, Ki, Kii):
    """General reversible inhibition. Ki: binds free E (raises apparent Km);
    Kii: binds ES (lowers apparent Vmax). Competitive: Kii -> inf; uncompetitive: Ki -> inf."""
    return V * S / (K * (1 + I / Ki) + S * (1 + I / Kii))


def aic(rss, n, k):
    """Akaike information criterion for least squares with n points and k parameters (small-sample corrected)."""
    a = n * math.log(rss / n) + 2 * k
    return a + 2 * k * (k + 1) / (n - k - 1)


# ---------- protein stability ----------
def dG_unfold(T, Tm, dHm, dCp):
    """Gibbs-Helmholtz stability curve, J/mol. T, Tm in K; dHm in J/mol; dCp in J/(mol K)."""
    return dHm * (1 - T / Tm) - dCp * ((Tm - T) + T * np.log(T / Tm))


def two_state_signal(dG, T, yN, yU):
    """Observed signal for a two-state N <-> U equilibrium with native and unfolded signals yN, yU."""
    fU = 1.0 / (1.0 + np.exp(dG / (R * T)))
    return yN + (yU - yN) * fU


# ---------- structures ----------
def read_pdb(path):
    """Atoms of a PDB file as a list of dicts: rec, name, res, chain, num, el, xyz (numpy array)."""
    path = Path(path)
    if not path.is_absolute() and not path.exists():
        path = DATA / path
    atoms = []
    for line in path.read_text().splitlines():
        if line.startswith("ENDMDL"):
            break
        if line.startswith(("ATOM", "HETATM")) and line[16] in " A":
            el = line[76:78].strip() or line[12:14].strip()
            atoms.append(dict(rec=line[:6].strip(), name=line[12:16].strip(), res=line[17:20].strip(),
                              chain=line[21], num=int(line[22:26]), el=el.upper(),
                              xyz=np.array([float(line[30:38]), float(line[38:46]), float(line[46:54])])))
    return atoms


def find_atom(atoms, res, num, name):
    for a in atoms:
        if a["res"] == res and a["num"] == num and a["name"] == name:
            return a
    raise KeyError(f"{res}{num}:{name} not in structure")


