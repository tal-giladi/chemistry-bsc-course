"""Regenerate the generated (not measured) data files of the Module 29 labs.

Run:  py make_data.py
The files are already in the folder; you only need this to see exactly how they were made or to make
a fresh noisy copy with another seed (py make_data.py 7). Every parameter is written at the top of
each file. The real data files (invertase_initial_rates.csv, glycolysis_rbc.csv, data/4CHA_site.pdb)
are not touched.
"""
import sys

import numpy as np

from enz29 import HERE, R, T25, dG_unfold, mixed, two_state_signal

SEED = int(sys.argv[1]) if len(sys.argv) > 1 else 29


def write(name, header_lines, columns, rows):
    with open(HERE / name, "w", encoding="utf-8", newline="\n") as f:
        for h in header_lines:
            f.write(f"# {h}\n")
        f.write(",".join(columns) + "\n")
        for r in rows:
            f.write(",".join(r) + "\n")
    print(f"wrote {name} ({len(rows)} rows)")


def protein_melts(rng):
    Tm, dHm, dCp = 337.15, 380e3, 6000.0           # K, J/mol, J/(mol K)
    dG25, m = float(dG_unfold(T25, Tm, dHm, dCp)), 7000.0   # J/mol, J/(mol M)
    T = np.arange(20.0, 90.5, 1.0) + 273.15
    yN = -12.0 + 0.020 * (T - 298.15)               # native CD at 222 nm, mdeg
    yU = -2.5 + 0.010 * (T - 298.15)                # unfolded
    sig = two_state_signal(dG_unfold(T, Tm, dHm, dCp), T, yN, yU) + rng.normal(0, 0.15, T.size)
    write("protein_thermal_melt.csv",
          ["GENERATED by make_data.py (not measured): two-state thermal unfolding of a model ~100-residue protein",
           "followed by CD at 222 nm. Parameters: Tm = 64.0 C, dHm = 380 kJ/mol, dCp = 6.0 kJ/(mol K),",
           "native baseline -12.0 + 0.020 (T - 25 C), unfolded -2.5 + 0.010 (T - 25 C) mdeg, noise SD 0.15 mdeg."],
          ["T_C", "cd222_mdeg"], [(f"{t - 273.15:.1f}", f"{s:.3f}") for t, s in zip(T, sig)])
    D = np.arange(0.0, 8.01, 0.25)
    dG = dG25 - m * D
    sig = two_state_signal(dG, T25, -12.0 + 0.10 * D, -2.5 + 0.05 * D) + rng.normal(0, 0.15, D.size)
    write("protein_urea_melt.csv",
          ["GENERATED by make_data.py (not measured): urea unfolding of the same model protein at 25 C, CD 222 nm.",
           f"Parameters: dG(H2O) = {dG25 / 1000:.2f} kJ/mol (the Gibbs-Helmholtz value at 25 C), m = 7.0 kJ/(mol M),",
           "native baseline -12.0 + 0.10 [urea], unfolded -2.5 + 0.05 [urea] mdeg, noise SD 0.15 mdeg."],
          ["urea_M", "cd222_mdeg"], [(f"{d:.2f}", f"{s:.3f}") for d, s in zip(D, sig)])


def invertase_fructose(rng):
    V, K, Ki = 3.91, 16.7, 58.0                     # arb., mM, mM (1913 constants; fructose competitive)
    rows = []
    for I in (0.0, 50.0, 100.0, 200.0):
        for S in (5.2, 10.4, 20.8, 41.6, 83.3, 166.7):
            v = mixed(S, I, V, K, Ki, np.inf) * (1 + rng.normal(0, 0.02))
            rows.append((f"{I:g}", f"{S:g}", f"{v:.3f}"))
    write("invertase_fructose_rates.csv",
          ["GENERATED by make_data.py (not measured): invertase initial rates with added fructose, simulated from",
           "the 1913 constants of Michaelis and Menten: V = 3.91 (arb.), Km = 16.7 mM, fructose competitive, Ki = 58 mM.",
           "Relative noise SD 2 %. Michaelis and Menten measured Ki for fructose with a different experimental design."],
          ["fructose_mM", "sucrose_mM", "rate_arb"], rows)


def chymotrypsin_ph(rng):
    kmax, pKa1, pKa2 = 2.0e5, 6.9, 8.9             # M^-1 s^-1
    rows = []
    for pH in np.arange(5.0, 10.51, 0.5):
        k = kmax / (1 + 10 ** (pKa1 - pH) + 10 ** (pH - pKa2)) * np.exp(rng.normal(0, 0.05))
        rows.append((f"{pH:.1f}", f"{k:.4g}"))
    write("chymotrypsin_ph_rate.csv",
          ["GENERATED by make_data.py (not measured): kcat/Km of a chymotrypsin-like serine protease against pH.",
           "Model: kcat/Km = kmax / (1 + 10^(pKa1 - pH) + 10^(pH - pKa2)), kmax = 2.0e5 M^-1 s^-1, pKa1 = 6.9 (His57),",
           "pKa2 = 8.9 (the Ile16 amino group that holds the active conformation). Log-normal noise SD 5 %."],
          ["pH", "kcat_over_Km_per_M_per_s"], rows)


def practical(rng):
    V, K = 120.0, 0.50                              # uM/min, mM
    inhibitors = {  # name: (I values in mM, Ki, Kii)
        "none": ((0.0,), np.inf, np.inf),
        "X": ((0.2, 0.5), 0.20, np.inf),            # competitive
        "Y": ((0.5, 1.5), np.inf, 0.80),            # uncompetitive
        "Z": ((0.3, 0.9), 0.30, 1.20),              # mixed
    }
    S_values = (0.10, 0.20, 0.40, 0.80, 1.60, 3.20)
    rows = []
    for name, (Is, Ki, Kii) in inhibitors.items():
        for I in Is:
            for S in S_values:
                for rep in (1, 2):
                    v0 = mixed(S, I, V, K, Ki, Kii)
                    v = v0 * (1 + rng.normal(0, 0.04)) + rng.normal(0, 0.8)
                    rows.append((name, f"{I:g}", f"{S:g}", str(rep), f"{v:.2f}"))
    write("practical_rates.csv",
          ["GENERATED by make_data.py (not measured): initial rates of enzyme E1, the first step of a two-step pathway,",
           "without inhibitor and with three candidate drug molecules X, Y and Z.",
           "Duplicate runs. Noise: 4 % relative plus 0.8 uM/min absolute (SD). The true parameters are in",
           "make_data.py; do not look until you have written your answer."],
          ["inhibitor", "I_mM", "S_mM", "replicate", "v_uM_per_min"], rows)


if __name__ == "__main__":
    rng = np.random.default_rng(SEED)
    protein_melts(rng)
    invertase_fructose(rng)
    chymotrypsin_ph(rng)
    practical(rng)
