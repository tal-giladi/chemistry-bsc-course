"""Regenerate the small example data sets for Module 05.

All files are generated from known models with a fixed random seed, so they are realistic but not
measured. Each block states its model and parameters, so you can check your answers. Run:

    py make_data.py
"""
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
rng = np.random.default_rng(2026)


def write_text(name, text):
    (HERE / name).write_text(text, encoding="utf-8", newline="\n")  # LF on every OS
    print(f"wrote {name} ({text.count(chr(10))} lines)")


# 1. Lesson 03: calibration line of a blue food dye at 630 nm, 1.00 cm cell (illustrative).
#    Model A = 0.004 + 0.1050 c (c in umol/L), absorbance noise sd 0.004.
#    Unknown: true c = 3.70 umol/L, read three times.
c_std = np.array([0.0, 1.0, 2.0, 4.0, 6.0, 8.0])
A_std = 0.004 + 0.1050 * c_std + 0.004 * rng.standard_normal(c_std.size)
A_unk = 0.004 + 0.1050 * 3.70 + 0.004 * rng.standard_normal(3)
lines = ["sample,c_umol_per_L,A630"]
lines += [f"standard,{c:.1f},{a:.4f}" for c, a in zip(c_std, A_std)]
lines += [f"unknown,,{a:.4f}" for a in A_unk]
write_text("calibration_dye.csv", "\n".join(lines) + "\n")

# 2. Lesson 03: fading of a dye, first order with a small constant baseline.
#    Model A(t) = 0.950 exp(-0.0230 t) + 0.020 (t in min). Noise sd = 0.002 + 0.025 A (bigger at
#    high absorbance); the instrument's estimate of that sd is given in column sigma_A.
t = np.arange(0, 121, 5.0)
A_true = 0.950 * np.exp(-0.0230 * t) + 0.020
sig = 0.002 + 0.025 * A_true
A_meas = A_true + sig * rng.standard_normal(t.size)
lines = ["t_min,A,sigma_A"] + [f"{a:.0f},{b:.4f},{s:.4f}" for a, b, s in zip(t, A_meas, sig)]
write_text("dye_fading.csv", "\n".join(lines) + "\n")

# 3. Lesson 04: a UV-Vis export in the style of a European instrument PC: metadata lines,
#    semicolons, decimal commas, units in the header. Spectrum: main band 629 nm (width 40 nm,
#    height 0.812), shoulder 580 nm (0.18), weak band 410 nm (0.045), baseline 0.006, noise 0.0015.
lam = np.arange(350, 751, 1.0)
A = (0.812 * np.exp(-0.5 * ((lam - 629) / 40) ** 2) + 0.18 * np.exp(-0.5 * ((lam - 580) / 30) ** 2)
     + 0.045 * np.exp(-0.5 * ((lam - 410) / 25) ** 2) + 0.006 + 0.0015 * rng.standard_normal(lam.size))
head = ["Instrument;Example UV-Vis (simulated data for this course)", "Sample;Blue drink, diluted 1:10",
        "Operator;course", "Date;2026-10-12 14:05", "Path length [cm];1,000",
        "Scan speed [nm/min];600", "Slit width [nm];2,0", ""]
rows = [f"{l:.1f};{a:.4f}".replace(".", ",") for l, a in zip(lam, A)]
write_text("uvvis_export.csv", "\n".join(head + ["Wavelength [nm];Absorbance [A]"] + rows) + "\n")

# 4. Lesson 04: a synthetic IR spectrum in JCAMP-DX 4.24 AFFN form (X++(Y..Y)), laid out like a
#    NIST WebBook gas-phase file: 450-3966 cm-1, step 4, 880 points, integers times YFACTOR.
#    Bands (absorbance, Gaussian, centre/height/width cm-1): 3660/0.08/25, 2975/0.55/30,
#    2900/0.30/30, 1460/0.10/20, 1390/0.08/15, 1065/0.92/18, 880/0.20/15.
nu = 450.0 + 4.0 * np.arange(880)
bands = [(3660, 0.08, 25), (2975, 0.55, 30), (2900, 0.30, 30), (1460, 0.10, 20), (1390, 0.08, 15),
         (1065, 0.92, 18), (880, 0.20, 15)]
y = sum(h * np.exp(-0.5 * ((nu - c) / w) ** 2) for c, h, w in bands)
y = np.clip(y + 0.002 * rng.standard_normal(nu.size), 0, None)
yfactor = 0.0001
iy = np.round(y / yfactor).astype(int)
hdr = ["##TITLE=Synthetic gas-phase IR spectrum (course example, not a real compound)",
       "##JCAMP-DX=4.24", "##DATA TYPE=INFRARED SPECTRUM",
       "##ORIGIN=Generated by labs/module-05/make_data.py", "##OWNER=public domain",
       "##STATE=gas", "##XUNITS=1/CM", "##YUNITS=ABSORBANCE", "##XFACTOR=1.0",
       f"##YFACTOR={yfactor}", "##DELTAX=4.0", "##FIRSTX=450.0", "##LASTX=3966.0",
       f"##FIRSTY={iy[0] * yfactor:.6f}", "##MAXX=3966", "##MINX=450",
       f"##MAXY={iy.max() * yfactor:.6f}", "##MINY=0", "##NPOINTS=880", "##XYDATA=(X++(Y..Y))"]
data = [f"{nu[i]:.1f} " + " ".join(str(v) for v in iy[i:i + 10]) for i in range(0, 880, 10)]
write_text("example_ir.jdx", "\n".join(hdr + data + ["##END="]) + "\n")

# 5. Lesson 05 practical: densities of sucrose standards and an unknown soft drink, measured as
#    in lesson 01.5 but with a 0.01 g pocket scale. Raw format of labs/module-01 (5 fills of a
#    20 mL syringe per repeat). True densities: a smooth cubic through the reference table
#    (0, 10, 20, 30 % at 20 C: 0.99823, 1.03814, 1.08096, 1.12698 g/mL). Syringe delivery
#    random sd 0.15 % per repeat, no bias. Unknowns: a regular soft drink, true w = 9.8 %, and a
#    diet soft drink, true w = 0.3 % (sweeteners, acids and dissolved CO2 are ignored).
ref_w = np.array([0, 10, 20, 30.0])
ref_rho = np.array([0.99823, 1.03814, 1.08096, 1.12698])
cubic = np.polyfit(ref_w, ref_rho, 3)
lines = ["sample,w_percent,repeat,fills,fill_volume_mL,cup_empty_g,cup_full_g,temp_C"]
for name, w in [("water", 0), ("sugar 5%", 5), ("sugar 10%", 10), ("sugar 15%", 15),
                ("sugar 20%", 20), ("sugar 25%", 25), ("sugar 30%", 30), ("soft drink", 9.8),
                ("diet soft drink", 0.3)]:
    w_true, w = w, (None if "drink" in name else w)
    for r in range(1, 6):
        empty = 150 + 3 * rng.random()
        vol = 100.0 * (1 + 0.0015 * rng.standard_normal())
        full = empty + np.polyval(cubic, w_true) * vol
        lines.append(f"{name},{'' if w is None else w},{r},5,20,{empty:.2f},{full:.2f},20.0")
write_text("density_raw.csv", "\n".join(lines) + "\n")
