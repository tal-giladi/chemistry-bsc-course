"""Lesson 33.3 (reference solution): one poster figure that carries one message.

Run from this folder:
    py lesson03_poster_figure_solution.py
    py lesson03_poster_figure_solution.py my_parity.csv     (columns molecule,mode,nu_exp_cm1,nu_calc_cm1)
Default data: example_parity.csv (GENERATED by make_data.py, not real spectra).
Steps:
  1. fit the scale factor through the origin and compute the RMS error before and after scaling;
  2. draw a residual plot (calculated minus measured, against measured) at its final printed size,
     22 x 18 cm on an A0 poster, with 24 pt labels so it reads from 2 m. A parity plot (calculated
     against measured) hides a 4 % error behind the y = x line; residuals show it at once;
  3. give it a title that states the result, not the topic.
Writes runs/poster_residuals.png (300 dpi at printed size) and prints the numbers for the poster text.
"""
import csv
import sys
from pathlib import Path

import numpy as np
import matplotlib
matplotlib.use("Agg")
from matplotlib import pyplot as plt

HERE = Path(__file__).resolve().parent
CM = 1 / 2.54
POSTER_PT = 24


def read_parity(path):
    with open(path, encoding="utf-8") as f:
        rows = list(csv.DictReader(f))
    return (np.array([float(r["nu_exp_cm1"]) for r in rows]),
            np.array([float(r["nu_calc_cm1"]) for r in rows]))


def rms(a, b):
    return float(np.sqrt(np.mean((a - b) ** 2)))


def summary(e, c):
    """Scale factor through the origin, RMS before and after scaling (cm-1), number of modes."""
    s = float(np.sum(e * c) / np.sum(c ** 2))
    return s, rms(c, e), rms(s * c, e), len(e)


def conclusion_title(s, before, after):
    """A title that states the result."""
    return f"Scaling by {s:.3f} cuts the RMS error\nfrom {before:.0f} to {after:.0f} cm$^{{-1}}$"


def main(argv):
    path = Path(argv[1]) if len(argv) > 1 else HERE / "example_parity.csv"
    e, c = read_parity(path)
    s, before, after, n = summary(e, c)
    print(f"{n} modes: scale factor {s:.4f}; RMS {before:.1f} cm-1 unscaled, {after:.1f} cm-1 scaled")
    plt.rcParams.update({"font.size": POSTER_PT, "axes.linewidth": 2})
    fig, ax = plt.subplots(figsize=(22 * CM, 18 * CM), layout="constrained")
    ax.axhline(0, color="0.4", lw=2)
    ax.scatter(e, c - e, s=60, color="#0072B2", label="unscaled")
    ax.scatter(e, s * c - e, s=60, color="#E69F00", marker="s", label=f"scaled x {s:.3f}")
    ax.set(xlabel="measured (cm$^{-1}$)", ylabel="calculated $-$ measured (cm$^{-1}$)")
    ax.set_title(conclusion_title(s, before, after), fontsize=POSTER_PT, loc="left")
    ax.legend(frameon=False, fontsize=POSTER_PT - 4, loc="upper left")
    out = HERE / "runs"
    out.mkdir(exist_ok=True)
    fig.savefig(out / "poster_residuals.png", dpi=300)
    print("title:", conclusion_title(s, before, after).replace('$^{-1}$', '-1').replace(chr(10), ' '))
    print("wrote runs/poster_residuals.png at 22 x 18 cm, 300 dpi")


if __name__ == "__main__":
    main(sys.argv)
